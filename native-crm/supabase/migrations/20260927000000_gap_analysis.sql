-- Minimal Supabase schema for Contextward's read-only Gap analysis connector.
-- Contextward selects active gap_clusters and embeds the one-to-one gap_scores row.
-- No sample rows are inserted; original gap data was not found locally.

create table if not exists public.gap_clusters (
    id bigint generated by default as identity primary key,
    market_key text not null,
    category text,
    cluster_label text not null,
    summary text,
    status text not null default 'active' check (status in ('active', 'retired')),
    created_at timestamptz not null default now()
);

create index if not exists gap_clusters_active_id_idx
    on public.gap_clusters (id)
    where status = 'active';

create table if not exists public.gap_scores (
    id bigint generated by default as identity primary key,
    cluster_id bigint not null unique
        references public.gap_clusters (id) on delete cascade,
    total_score double precision check (total_score between 0 and 1),
    frequency_score double precision check (frequency_score between 0 and 1),
    intensity_score double precision check (intensity_score between 0 and 1),
    breadth_score double precision check (breadth_score between 0 and 1),
    wtp_score double precision check (wtp_score between 0 and 1),
    workaround_score double precision check (workaround_score between 0 and 1),
    segment_score double precision check (segment_score between 0 and 1)
);

alter table public.gap_clusters enable row level security;
alter table public.gap_scores enable row level security;

grant select on public.gap_clusters, public.gap_scores to anon, authenticated;

drop policy if exists "read active gap clusters" on public.gap_clusters;
create policy "read active gap clusters"
    on public.gap_clusters for select to anon, authenticated
    using (status = 'active');

drop policy if exists "read scores for active gap clusters" on public.gap_scores;
create policy "read scores for active gap clusters"
    on public.gap_scores for select to anon, authenticated
    using (
        exists (
            select 1 from public.gap_clusters
            where gap_clusters.id = gap_scores.cluster_id
              and gap_clusters.status = 'active'
        )
    );
